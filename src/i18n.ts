export function isSupportedLanguage(value: unknown): value is SoleilLanguage {
  return (
    typeof value === "string" &&
    (SUPPORTED_LANGUAGES as readonly string[]).includes(value.toLowerCase())
  );
}

export function normalizeLanguage(value: string | undefined): SoleilLanguage | undefined {
  if (!value) return undefined;
  const code = value.trim().toLowerCase().split(/[-_]/)[0];
  return isSupportedLanguage(code) ? code : undefined;
}

export function detectSystemLanguage(): SoleilLanguage {
  return normalizeLanguage(Intl.DateTimeFormat().resolvedOptions().locale) || "en";
}

export function translate(
  language: SoleilLanguage | undefined,
  key: MessageKey,
  variables: Record<string, string | number> = {},
): string {
  let value = TRANSLATIONS[language || "en"]?.[key] || ENGLISH_MESSAGES[key];
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}
